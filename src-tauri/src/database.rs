pub fn get_target(conn: &Connection, project_id: &str) -> Result<Option<DatabaseTarget>, String> {
    let mut stmt = conn
        .prepare(
            "SELECT id, project_id, provider, database_url, container_name, compose_file
             FROM database_targets WHERE project_id = ?1",
        )
        .map_err(|e| e.to_string())?;
    let mut rows = stmt
        .query_map(rusqlite::params![project_id], |row| {
            Ok(DatabaseTarget {
                id: row.get(0)?,
                project_id: row.get(1)?,
                provider: row.get(2)?,
                database_url: row.get(3)?,
                container_name: row.get(4)?,
                compose_file: row.get(5)?,
            })
        })
        .map_err(|e| e.to_string())?;
    match rows.next() {
        Some(row) => Ok(Some(row.map_err(|e| e.to_string())?)),
        None => Ok(None),
    }
}

pub fn record_target(
    conn: &Connection,
    project_id: &str,
    provider: &str,
    database_url: &str,
    container_name: Option<&str>,
    compose_file: Option<&str>,
) -> Result<DatabaseTarget, String> {
    let now = chrono::Utc::now().to_rfc3339();
    let id = format!("dbt-{}", uuid::Uuid::new_v4());
    conn.execute(
        "INSERT INTO database_targets
            (id, project_id, provider, database_url, container_name, compose_file, created_at, updated_at)
         VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?7)
         ON CONFLICT(project_id) DO UPDATE SET
            provider = excluded.provider,
            database_url = excluded.database_url,
            container_name = excluded.container_name,
            compose_file = excluded.compose_file,
            updated_at = excluded.updated_at",
        rusqlite::params![id, project_id, provider, database_url, container_name, compose_file, now],
    )
    .map_err(|e| e.to_string())?;
    get_target(conn, project_id)?
        .ok_or_else(|| "database target vanished after recording".to_string())
}

