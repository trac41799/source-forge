// src-tauri/src/database.rs
//
// Local-first database targets (Docker Postgres on this machine).
//
// Postgres-backed stacks no longer hard-require a Supabase cloud project up
// front: when no cloud config exists, the pipeline provisions a containerized
// Postgres locally, applies the Prisma schema against it, and verifies
// reachability + tables. Prisma is the portability layer — the same schema
// applies anywhere later (Supabase cloud, Neon, RDS) by changing only
// DATABASE_URL, and data moves with pg_dump/pg_restore (Supabase is Postgres).

use rusqlite::Connection;
use serde::{Deserialize, Serialize};
use std::path::Path;

/// Docker image for the local database (pinned for reproducibility).
pub const LOCAL_DB_IMAGE: &str = "postgres:16-alpine";
/// Host port (Supabase-local convention; avoids clashing with a local 5432).
pub const LOCAL_DB_PORT: u16 = 54322;
pub const LOCAL_DB_USER: &str = "postgres";
pub const LOCAL_DB_NAME: &str = "postgres";
/// Password when POSTGRES_PASSWORD is unset. Local-dev only; never commit it.
pub const LOCAL_DB_PASSWORD_FALLBACK: &str = "postgres";

/// How long to wait for the container to accept connections.
const HEALTH_TIMEOUT_SECS: u64 = 120;

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct DatabaseTarget {
    pub id: String,
    pub project_id: String,
    pub provider: String,
    pub database_url: String,
    pub container_name: Option<String>,
    pub compose_file: Option<String>,
}

#[derive(Debug, Clone, PartialEq)]
pub enum ProvisionError {
    /// Docker is unavailable (daemon down / CLI missing): the operator can fix
    /// this, so the run should pause, not fail.
    DaemonDown(String),
    /// Anything else: a real failure.
    Failed(String),
}

impl std::fmt::Display for ProvisionError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ProvisionError::DaemonDown(detail) => write!(f, "docker unavailable: {detail}"),
            ProvisionError::Failed(detail) => write!(f, "{detail}"),
        }
    }
}

