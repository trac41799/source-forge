fn docker(args: &[&str]) -> Result<(bool, String), String> {
    let output = std::process::Command::new("docker")
        .args(args)
        .output()
        .map_err(|e| format!("cannot start docker: {e}"))?;
    let mut text = String::from_utf8_lossy(&output.stdout).to_string();
    text.push_str(&String::from_utf8_lossy(&output.stderr));
    Ok((output.status.success(), text.trim().to_string()))
}

fn daemon_up() -> bool {
    docker(&["info"]).map(|(ok, _)| ok).unwrap_or(false)
}

fn container_id(compose_file: &str, slug: &str) -> Result<String, String> {
    let (ok, out) = docker(&[
        "compose",
        "-f",
        compose_file,
        "-p",
        slug,
        "ps",
        "-q",
        "db",
    ])?;
    if !ok {
        return Err(format!("docker compose ps failed: {out}"));
    }
    let id = out.lines().next().unwrap_or_default().trim().to_string();
    if id.is_empty() {
        return Err("no container id reported for the db service".to_string());
    }
    Ok(id)
}

fn wait_healthy(container: &str) -> Result<(), String> {
    let deadline = std::time::Instant::now() + std::time::Duration::from_secs(HEALTH_TIMEOUT_SECS);
    loop {
        match docker(&["exec", container, "pg_isready", "-U", LOCAL_DB_USER]) {
            Ok((true, _)) => return Ok(()),
            _ => {
                if std::time::Instant::now() >= deadline {
                    return Err(format!(
                        "postgres did not become healthy within {HEALTH_TIMEOUT_SECS}s"
                    ));
                }
                std::thread::sleep(std::time::Duration::from_secs(2));
            }
        }
    }
}

