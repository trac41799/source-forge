/// `docker-compose.yml` for the local database. The app's DATABASE_URL points
/// at it; only the URL changes when migrating to hosted Postgres later.
pub fn render_compose_yml(password: &str) -> String {
    // NOTE: a raw string with lines starting at column 0. Rust `\`-continuations
    // strip leading whitespace, which once flattened this whole file and
    // produced a duplicate `volumes:` key that only a live `docker compose up`
    // caught. Keep it raw and column-aligned.
    format!(
        r#"# Generated by SourceForge: local Postgres for this project.
# `docker compose up -d db` starts it; the same Prisma schema migrates
# anywhere later (Supabase cloud, Neon, RDS) by changing DATABASE_URL.
services:
  db:
    image: {image}
    environment:
      POSTGRES_USER: {user}
      POSTGRES_PASSWORD: {password}
      POSTGRES_DB: {name}
    ports:
      - "{port}:5432"
    volumes:
      - pgdata:/var/lib/postgresql/data
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U {user}"]
      interval: 5s
      timeout: 3s
      retries: 12
volumes:
  pgdata: {{}}
"#,
        image = LOCAL_DB_IMAGE,
        user = LOCAL_DB_USER,
        password = password,
        name = LOCAL_DB_NAME,
        port = LOCAL_DB_PORT,
    )
}

/// Human-readable local database URL for the given password.
pub fn local_database_url(password: &str) -> String {
    format!(
        "postgresql://{user}:{password}@localhost:{port}/{name}",
        user = LOCAL_DB_USER,
        password = password,
        port = LOCAL_DB_PORT,
        name = LOCAL_DB_NAME,
    )
}

/// Password from the environment, falling back to the local-dev default.
pub fn local_db_password() -> String {
    std::env::var("POSTGRES_PASSWORD")
        .ok()
        .filter(|value| !value.trim().is_empty())
        .unwrap_or_else(|| LOCAL_DB_PASSWORD_FALLBACK.to_string())
}

/// Compose project slug derived from the project directory name.
pub fn compose_slug(project_path: &str) -> String {
    let base = Path::new(project_path)
        .file_name()
        .and_then(|name| name.to_str())
        .unwrap_or("app");
    let mut slug: String = base
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '-' })
        .collect();
    slug = slug.trim_matches('-').to_string();
    if slug.is_empty() {
        slug = "app".to_string();
    }
    slug.truncate(40);
    slug
}

/// True when the command output smells like a dead Docker daemon.
pub fn docker_daemon_down(output: &str) -> bool {
    let lower = output.to_lowercase();
    lower.contains("cannot connect to the docker daemon")
        || lower.contains("error during connect")
        || lower.contains("is the docker daemon running")
        || lower.contains("dockerdesktoplinuxengine")
        || lower.contains("the system cannot find the file specified")
}

/// Prisma model names in a schema file (`model User { ... }`).
pub fn prisma_models(schema: &str) -> Vec<String> {
    let mut models = Vec::new();
    for line in schema.lines() {
        let trimmed = line.trim_start();
        if let Some(rest) = trimmed.strip_prefix("model ") {
            let name: String = rest
                .chars()
                .take_while(|c| c.is_alphanumeric() || *c == '_')
                .collect();
            if !name.is_empty() {
                models.push(name);
            }
        }
    }
    models
}

/// Datasource provider declared in the schema (`postgresql`|`sqlite`|...).
/// Scoped to the `datasource` block: the `generator` block also declares a
/// `provider` (`prisma-client-js`).
pub fn schema_provider(schema: &str) -> String {
    let mut in_datasource = false;
    for line in schema.lines() {
        let trimmed = line.trim();
        if trimmed.starts_with("datasource ") {
            in_datasource = true;
            continue;
        }
        if trimmed.starts_with('}') {
            in_datasource = false;
            continue;
        }
        if in_datasource {
            if let Some(rest) = trimmed.strip_prefix("provider") {
                let value: String = rest
                    .trim_start_matches([' ', '=', '\t'])
                    .trim_matches(['\"', '\''])
                    .chars()
                    .take_while(|c| c.is_alphanumeric() || *c == '-' || *c == '_')
                    .collect();
                if !value.is_empty() {
                    return value;
                }
            }
        }
    }
    "postgresql".to_string()
}

/// SQL that resolves each model to its table (NULL / missing row = missing).
/// `to_regclass` is Postgres-only; SQLite exposes `sqlite_master`.
pub fn schema_check_sql(models: &[String], provider: &str) -> String {
    if provider == "sqlite" {
        models
            .iter()
            .map(|model| {
                format!("SELECT name FROM sqlite_master WHERE type='table' AND name='{model}';")
            })
            .collect::<Vec<_>>()
            .join("\n")
    } else {
        models
            .iter()
            .map(|model| format!("SELECT to_regclass('public.\"{model}\"');"))
            .collect::<Vec<_>>()
            .join("\n")
    }
}

/// Models with no matching table in the query output.
pub fn missing_tables(stdout: &str, models: &[String], provider: &str) -> Vec<String> {
    models
        .iter()
        .filter(|model| {
            if provider == "sqlite" {
                !stdout.lines().any(|line| {
                    let cell = line.trim().trim_matches('"');
                    cell == model.as_str()
                })
            } else {
                !stdout.contains(&format!("public.\"{model}\""))
                    && !stdout.contains(&format!("public.{model}"))
            }
        })
        .map(|model| model.to_string())
        .collect()
}

